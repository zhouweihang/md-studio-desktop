const CATALOGS: Record<Locale, Catalog> = { 'zh-CN': ZH, en: EN };

const warned = new Set<string>();

/** 取文案；缺键回退中文，再缺则返回键名（并只告警一次）。 */
export function t(key: UiKey, vars?: Record<string, string | number>, locale: Locale = 'zh-CN'): string {
  const catalog = CATALOGS[locale] ?? CATALOGS['zh-CN'];
  let template: string = catalog[key] ?? ZH[key];
  if (!template) {
    if (!warned.has(key)) {
      warned.add(key);
      console.warn(`[md-studio] 缺少界面文案：${key}`);
    }
    template = key;
  }
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    vars[name] === undefined ? match : String(vars[name])
  );
}

/** 命令标签（中文取自命令表，英文取自本目录）。 */
export function commandLabel(id: string, fallbackZh: string, locale: Locale): string {
  if (locale === 'zh-CN') return fallbackZh;
  return COMMAND_LABELS_EN[id] ?? fallbackZh;
}

/** 目录键集合（用于测试与缺键告警）。 */
export function catalogKeys(locale: Locale): string[] {
  return Object.keys(CATALOGS[locale] ?? {});
}

/** 中文目录键集合（`EN` 的完整性由类型检查保证）。 */
export function zhCatalogKeys(): string[] {
  return Object.keys(ZH);
}

export function isLocale(value: unknown): value is Locale {
  return value === 'zh-CN' || value === 'en';
}
