interface EmojiEntry {
  char: string;
  /** 规范短代码（第一个别名） */
  name: string;
  aliases: string[];
}

const ENTRIES: EmojiEntry[] = [];
const BY_ALIAS = new Map<string, EmojiEntry>();

for (const rawLine of TABLE.split('\n')) {
  const line = rawLine.trim();
  if (!line) continue;
  const spaceIndex = line.indexOf(' ');
  if (spaceIndex <= 0) continue;
  const char = line.slice(0, spaceIndex);
  const aliases = line
    .slice(spaceIndex + 1)
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  if (aliases.length === 0) continue;
  const entry: EmojiEntry = { char, name: aliases[0]!, aliases };
  ENTRIES.push(entry);
  for (const alias of aliases) {
    if (!BY_ALIAS.has(alias)) BY_ALIAS.set(alias, entry);
  }
}

/** 短代码总数（含别名）。 */
export function emojiCount(): number {
  return ENTRIES.length;
}

/** 全部短代码条目（供自动补全构建索引）。 */
export function emojiEntries(): readonly EmojiEntry[] {
  return ENTRIES;
}

/** `:name:` → 字符；未知短代码返回 null。 */
export function emojiFor(name: string): string | null {
  return BY_ALIAS.get(name.trim().replace(/^:|:$/g, ''))?.char ?? null;
}

const SHORTCODE_RE = /:([a-zA-Z0-9_+-]+):/g;

/** 把文本中的 `:shortcode:` 替换为字符（未知短代码原样保留）。 */
export function replaceEmojiShortcodes(text: string): string {
  return text.replace(SHORTCODE_RE, (match, name: string) => BY_ALIAS.get(name)?.char ?? match);
}

export interface EmojiMatch {
  name: string;
  char: string;
  /** 规范短代码（首个别名） */
  canonical: string;
}

/** 前缀搜索（自动补全用）：按规范名优先、别名次之排序。 */
export function searchEmoji(query: string, limit = 24): EmojiMatch[] {
  const needle = query.toLowerCase();
  const exact: EmojiMatch[] = [];
  const prefixed: EmojiMatch[] = [];
  const contained: EmojiMatch[] = [];
  for (const entry of ENTRIES) {
    for (const alias of entry.aliases) {
      const match: EmojiMatch = { name: alias, char: entry.char, canonical: entry.name };
      if (alias === needle) exact.push(match);
      else if (alias.startsWith(needle)) prefixed.push(match);
      else if (needle.length >= 2 && alias.includes(needle)) contained.push(match);
      else continue;
      break;
    }
  }
  return [...exact, ...prefixed, ...contained].slice(0, limit);
}
